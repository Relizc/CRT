import assert from "node:assert/strict";
import { LabController } from "../src/lab-controller.js";
import { SMILEY_EMISSION_WINDOWS } from "../src/config.js";

const controller = new LabController();
assert.equal(controller.snapshot().valid, true);
assert.equal(controller.snapshot().settings.fireRate, 200);
assert.equal(controller.snapshot().settings.persistence, .3);
assert.equal(controller.signalData.length, 401);
controller.setSourceMode("single");
const electron = controller.fire();
controller.simulation.advance(.1);
const before = structuredClone(electron), phase = controller.simulation.emissions.phase;
controller.setSetting("brightness", "51");
assert.ok(controller.snapshot().settingsError);
assert.equal(controller.snapshot().canFire, false);
assert.equal(controller.fire(), undefined);
assert.equal(controller.simulation.cloud.particles.length, 1);
assert.deepEqual(electron, before);
controller.setSetting("brightness", "50");
assert.equal(controller.snapshot().settingsError, "");
assert.equal(controller.snapshot().settings.brightness, 50);
assert.equal(controller.simulation.emissions.phase, phase);
controller.setSetting("fireRate", "2.5");
assert.match(controller.snapshot().settingsError, /integer/);
controller.setSetting("fireRate", "200");
controller.setSetting("persistence", "");
assert.ok(controller.snapshot().settingsError);
controller.setSetting("persistence", ".3");
assert.equal(controller.snapshot().canFire, true);
const oldSnapshot = controller.snapshot();
controller.simulation.advance(.1);
assert.notEqual(oldSnapshot.activeElectron.physicalAge, controller.snapshot().activeElectron.physicalAge);
controller.seek(.45);
assert.equal(controller.snapshot().running, false);
assert.equal(controller.snapshot().time, .45);
assert.equal(controller.simulation.cloud.particles.length, 1);
controller.editEquation(0, "t+");
assert.equal(controller.snapshot().valid, false);
assert.ok(controller.snapshot().equationErrors[0]);
assert.equal(controller.snapshot().canFire, false);
controller.editEquation(0, "{t<.5:.1,-.1}");
assert.equal(controller.snapshot().valid, true);
assert.equal(controller.snapshot().currents.ix, .1);
controller.seek(.6);
assert.equal(controller.snapshot().currents.ix, -.1);
controller.editEquation(0, "sqrt(t-0.8)");
assert.ok(controller.snapshot().physicsError);
assert.equal(controller.snapshot().running, false);
controller.seek(.9);
controller.toggleRunning();
assert.equal(controller.snapshot().physicsError, "");
assert.ok(controller.snapshot().currents.ix > 0);
let clears = 0;
controller.onClearScreen = () => clears++;
controller.selectPreset("smiley");
assert.equal(controller.simulation.emissionWindows, SMILEY_EMISSION_WINDOWS);
assert.equal(controller.snapshot().hold, true);
assert.equal(controller.snapshot().sourceMode, "continuous");
assert.equal(controller.simulation.cloud.particles.length, 0);
assert.equal(clears, 1);
controller.editEquation(0, ".1");
assert.equal(controller.simulation.emissionWindows, null);
controller.selectPreset("triangle");
assert.equal(controller.simulation.emissionWindows, null);
assert.equal(controller.snapshot().activePreset, "triangle");
assert.equal(controller.snapshot().running, true);
assert.equal(clears, 2);
controller.setOption("loop", false);
controller.setOption("coils", false);
controller.setOption("speed", 2);
controller.setView("magnets");
assert.equal(controller.snapshot().loop, false);
assert.equal(controller.snapshot().options.coils, false);
assert.equal(controller.snapshot().options.speed, 2);
assert.equal(controller.snapshot().view, "magnets");
controller.restart();
assert.equal(clears, 3);
assert.equal(controller.snapshot().time, 0);
console.log("React controller passed: presets, independent firing, draft validation, stable snapshots, piecewise edits, domain recovery, demo blanking, visibility, seeking and restart.");
