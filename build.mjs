import { build } from "esbuild";
import {
  copyFile,
  cp,
  mkdir,
  readFile,
  readdir,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Prepare local third-party assets. Application modules stay separate and editable.
const root = path.dirname(fileURLToPath(import.meta.url));
const dependency = (...parts) => path.join(root, "node_modules", ...parts);
const vendor = path.join(root, "vendor");
await mkdir(vendor, { recursive: true });
await mkdir(path.join(root, "styles"), { recursive: true });
await copyFile(
  dependency("three", "build", "three.module.js"),
  path.join(vendor, "three.js"),
);
await copyFile(
  dependency("three", "build", "three.core.js"),
  path.join(vendor, "three.core.js"),
);
await copyFile(
  dependency("mathlive", "mathlive.min.mjs"),
  path.join(vendor, "mathlive.js"),
);
const addonRoot = dependency("three", "examples", "jsm");
await build({
  entryPoints: [
    "controls/OrbitControls.js",
    "lines/Line2.js",
    "lines/LineGeometry.js",
    "lines/LineMaterial.js",
  ].map((name) => path.join(addonRoot, name)),
  outbase: addonRoot,
  outdir: path.join(vendor, "addons"),
  bundle: true,
  splitting: true,
  format: "esm",
  external: ["three"],
  minify: true,
  legalComments: "inline",
  chunkNames: "chunks/[name]-[hash]",
});
await cp(dependency("mathlive", "fonts"), path.join(vendor, "fonts"), {
  recursive: true,
});
let fontCSS = "/* Local MathLive fonts; generated by npm run build. */\n";
for (const name of await readdir(dependency("mathlive", "fonts"))) {
  if (!name.endsWith(".woff2")) continue;
  const family = name.replace(/-[^-]+\.woff2$/, "");
  fontCSS += `@font-face{font-family:'${family}';src:url('../vendor/fonts/${name}') format('woff2');font-weight:${name.includes("Bold") ? "700" : "400"};font-style:${name.includes("Italic") ? "italic" : "normal"};font-display:block}\n`;
}
await writeFile(path.join(root, "styles", "fonts.css"), fontCSS);
const licenses = await Promise.all(
  ["three/LICENSE", "mathlive/LICENSE.txt"].map((name) =>
    readFile(dependency(name), "utf8"),
  ),
);
await writeFile(
  path.join(vendor, "LICENSES.txt"),
  `Three.js and MathLive are distributed under the MIT license.\n\n${licenses.join("\n\n")}`,
);
console.log(
  "Prepared local libraries and fonts. CRT.html loads the individual src/ modules.",
);
